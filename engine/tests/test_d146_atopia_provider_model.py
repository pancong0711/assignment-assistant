"""D146：Atopia 可选 provider / 模型（与 Playground 共用 `build_client_for`）。

此前 `/atopia/ask` 只接受 `model`，provider 固定取「评阅段」配置 →
Atopia 用不上别的 provider，其 `headers`（如 opencode-go 会话头）也未必生效。
"""
from __future__ import annotations

import pytest

from assist.grading import providers as P
from assist.grading.llm import LLMClient, LLMConfigError, build_client_for

GO = "https://opencode.ai/inference/go/openai/v1"
ALI = "https://dashscope.example/v1"


@pytest.fixture()
def ws(tmp_path):
    (tmp_path / "kb").mkdir()
    P.save_provider(tmp_path, "opencode-go", base_url=GO, api_key="k1", model="m-go",
                    headers={"x-opencode-session": "{session}"}, user_agent="ua-test")
    P.save_provider(tmp_path, "aliyun", base_url=ALI, api_key="k2", model="qwen")
    P.set_stage(tmp_path, "evaluation", provider="aliyun", model="qwen")
    return tmp_path


def test_pick_provider_uses_its_base_and_headers(ws):
    c, used = build_client_for(ws, "opencode-go")
    assert c.base_url == GO
    assert used == "m-go"
    assert c.extra_headers.get("x-opencode-session") == "{session}"
    h = c._headers_for("k1", {})
    assert h["x-opencode-session"].startswith("assist-")
    assert h["User-Agent"] == "ua-test"


def test_default_uses_evaluation_stage(ws):
    """不指定 provider → 与改动前一致（评阅段配置）。"""
    c, used = build_client_for(ws, "")
    assert c.base_url == ALI
    assert used == "qwen"
    assert "x-opencode-session" not in {k.lower() for k in c._headers_for("k2", {})}


def test_model_override(ws):
    c, used = build_client_for(ws, "opencode-go", "custom-model")
    assert used == "custom-model"
    assert c.model == "custom-model"


def test_unknown_provider_raises(ws):
    with pytest.raises(LLMConfigError) as ei:
        build_client_for(ws, "not-there")
    assert "不存在" in str(ei.value)


def test_provider_without_key_raises(ws):
    P.save_provider(ws, "nokey", base_url="https://x/v1")
    with pytest.raises(LLMConfigError) as ei:
        build_client_for(ws, "nokey")
    assert "api_key" in str(ei.value)


def test_session_id_autogenerated_and_stable(ws):
    c, _ = build_client_for(ws, "opencode-go", session_prefix="atopia")
    assert c.session_id.startswith("atopia-")
    h1 = c._headers_for("k1", {})["x-opencode-session"]
    h2 = c._headers_for("k1", {})["x-opencode-session"]
    assert h1 == h2 == c.session_id


def test_playground_and_atopia_share_logic(ws):
    """两条路径必须同源（防止口径漂移）。"""
    from assist.playground import ask as A
    pc, pm = A._client(ws, "opencode-go", "m-go")
    ac, am = build_client_for(ws, "opencode-go", "m-go", session_prefix="atopia")
    assert pc.base_url == ac.base_url
    assert pm == am
    assert pc.extra_headers == ac.extra_headers
    assert pc.session_id.startswith("playground-")
    assert ac.session_id.startswith("atopia-")
